#![no_main]

use libfuzzer_sys::fuzz_target;
use nacre_core::DigestAlgorithm;
use nacre_tsp::{Request, verify_response, verify_token};

// The SHA-256 imprint and the nonce of `tests/corpus/recorded/request.tsq`.
const IMPRINT: [u8; 32] = [
    0xac, 0x94, 0x15, 0x05, 0xb5, 0xd9, 0x36, 0x1d, 0x90, 0xbc, 0x04, 0x18, 0xf0, 0xaa, 0x3d, 0xe1,
    0xff, 0x70, 0x2a, 0x92, 0xca, 0x45, 0xcf, 0xca, 0x8c, 0x6e, 0x34, 0xb2, 0xec, 0x82, 0x7c, 0x3c,
];
const NONCE: [u8; 8] = [0xd4, 0x1c, 0xbf, 0xf4, 0xfd, 0xed, 0x9d, 0x81];

fuzz_target!(|data: &[u8]| {
    if let Ok(request) = Request::new(DigestAlgorithm::Sha256, &IMPRINT, &NONCE) {
        let _ = verify_response(data, &request);
    }
    let _ = verify_token(data, DigestAlgorithm::Sha256, &IMPRINT);
});
